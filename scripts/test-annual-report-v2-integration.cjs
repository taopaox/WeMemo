const {app,BrowserWindow,ipcMain,dialog}=require('electron')
const fs=require('fs'),path=require('path')
const root=path.resolve(__dirname,'..')
const {buildSync}=require(root+'/node_modules/esbuild')
const artifact=fs.mkdtempSync(path.join(require('os').tmpdir(),'wememo-v2-integration-'))
app.setPath('userData',path.join(artifact,'user-data'))
app.commandLine.appendSwitch('disable-background-timer-throttling')
buildSync({entryPoints:[root+'/electron/services/annualReportV2Service.ts'],bundle:true,platform:'node',format:'cjs',external:['electron'],outfile:artifact+'/service.cjs',logLevel:'silent'})
buildSync({entryPoints:[root+'/electron/services/annualReportV2Stats.ts'],bundle:true,platform:'node',format:'cjs',outfile:artifact+'/stats.cjs',logLevel:'silent'})
const {AnnualV2Accumulator}=require(artifact+'/stats.cjs')
const stats=new AnnualV2Accumulator(2024,'self')
for(let c=0;c<3;c++) {
 stats.addContact('friend'+c,{nick_name:'测试好友'+(c+1)})
 for(let month=0;month<12;month++)for(let day=1;day<10+c;day++)for(let n=0;n<4;n++)stats.add('friend'+c,{create_time:new Date(2024,month,day,9,0,n*10).getTime()/1000,computed_is_send:n%2,local_type:1,message_content:n%2?'一起吃饭[微笑]':'好呀明天见'})
}
const cards=stats.finish()
const runId=path.basename(artifact)
const html=path.join(root,'dist',runId+'.html'),js=path.join(root,'dist',runId+'.js')
buildSync({stdin:{contents:`import React from 'react';import{createRoot}from'react-dom/client';import{MemoryRouter}from'react-router-dom';import Page from './src/pages/AnnualReportV2Page';createRoot(document.getElementById('app')).render(<MemoryRouter><Page/></MemoryRouter>);`,resolveDir:root,loader:'tsx'},bundle:true,platform:'browser',format:'iife',loader:{'.scss':'empty'},outfile:js,logLevel:'silent'})
fs.writeFileSync(html,'<!doctype html><html><body style="margin:0"><div id="app" style="height:100vh"></div><style>.annual-v2-host{height:100%;position:relative}.annual-v2-host iframe{width:100%;height:100%;display:block;border:0}.annual-v2-host__status{position:absolute;bottom:0}</style><script src="./'+runId+'.js"></script></body></html>')
fs.writeFileSync(artifact+'/preload.cjs',`const {contextBridge,ipcRenderer}=require('electron');contextBridge.exposeInMainWorld('electronAPI',{config:{get:async k=>k==='myWxid'?'self':null},annualReport:{getAvailableYears:async()=>({success:true,data:[2024]})},annualReportV2:{onProgress:()=>()=>{},request:p=>p.method==='years'?Promise.resolve({ok:true,years:[2024]}):p.method==='analyze'?ipcRenderer.invoke('fixture:analyze',p):ipcRenderer.invoke('annualReportV2:request',p)}})`)
const watchdog=setTimeout(()=>{console.error('Integration test timed out');app.exit(1)},90000)
const pause=ms=>new Promise(r=>setTimeout(r,ms))
let count=0
app.whenReady().then(async()=>{
 require(artifact+'/service.cjs').registerAnnualReportV2(()=>({dbPath:'fixture',decryptKey:'fixture',myWxid:'self'}))
 ipcMain.handle('fixture:analyze',()=>{count++;return {ok:true,cards}})
 dialog.showSaveDialog=async(_win,opts)=>({canceled:false,filePath:path.join(artifact,opts.defaultPath)})
 const win=new BrowserWindow({width:1440,height:1000,show:false,webPreferences:{preload:artifact+'/preload.cjs',contextIsolation:true,sandbox:true}})
 const errors=[]
 win.webContents.on('console-message',(_e,level,message)=>{if(level>=2&&/ReferenceError|TypeError|Failed to resolve component/.test(message)){errors.push(message);console.log(message)}})
 await win.loadFile(html);await pause(1800)
 const frame=win.webContents.mainFrame.frames.find(f=>f.url.includes('annual-v2'))
 const run=code=>frame.executeJavaScript(code)
 console.log('Integrated iframe loaded; analysis runs:',count)
 if(count!==1)throw Error('Expected one analysis run shared between cards')
 await run("window.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown'}))")
 await pause(2300)
 await run("document.querySelector('.wf-trigger').click()")
 await pause(200)
 await run("document.querySelector('.wf-export').click()")
 for(let i=0;i<40;i++){await pause(500);if(fs.readdirSync(artifact).some(f=>f.endsWith('.png')))break}
 const files=fs.readdirSync(artifact).filter(f=>f.endsWith('.png'))
 if(!files.length)throw Error('PNG export did not finish: '+await run('document.body.innerText.slice(-900)'))
 console.log('Native PNG export passed:',files[0])
 // All-page export also verifies every card reaches an exportable final state.
 await run("document.querySelector('.wf-trigger').click()")
 await pause(200)
 await run("[...document.querySelectorAll('.wf-item')].find(e=>e.textContent.includes('9:16')).click()")
 await pause(400)
 await run("document.querySelector('.wf-export--zip').click()")
 for(let i=0;i<100;i++){await pause(500);if(fs.readdirSync(artifact).some(f=>f.endsWith('.zip')))break}
 const zips=fs.readdirSync(artifact).filter(f=>f.endsWith('.zip'))
 if(!zips.length)throw Error('ZIP export did not finish: '+await run('document.body.innerText.slice(-900)'))
 const JSZip=require(root+'/node_modules/jszip');const zip=await JSZip.loadAsync(fs.readFileSync(path.join(artifact,zips[0])))
 const entries=Object.keys(zip.files).filter(f=>f.endsWith('.png'))
 if(entries.length!==9)throw Error('Expected 9 exported pages, got '+entries.length)
 console.log('All-page ZIP export passed:',entries.length,'PNGs; analysis runs:',count)
 console.log('Test artifacts:',artifact)
 if(errors.length)throw Error(errors.join('\n'))
 fs.rmSync(html,{force:true});fs.rmSync(js,{force:true});clearTimeout(watchdog);app.exit(0)
}).catch(e=>{console.error(e);fs.rmSync(html,{force:true});fs.rmSync(js,{force:true});app.exit(1)})
